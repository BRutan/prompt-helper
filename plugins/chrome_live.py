#!/usr/bin/env python3
"""Build and update a local MV3 extension in ordinary Google Chrome.

On macOS, install uses Chrome's normal Load unpacked UI via Accessibility.
After that, the installed extension checks a build marker and reloads itself.
Never use Chromium, --load-extension, or a second profile.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import uuid
import zipfile

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / 'plugins' / 'chrome'
DEFAULT_OUT = ROOT / 'dist' / 'chrome'
EXTENSION_FOLDER = 'prompt-helper-chrome'
CHROME_URL = 'chrome://extensions'
SOURCE_FILES = (
    'manifest.json', 'session.js', 'background.js', 'build-watch.js',
    'content.js', 'delivery-content.js', 'response-monitor.js',
    'dashboard-bridge.js', 'popup.html', 'popup.js', 'runtime-config.js', 'session-layout.js', 'open-sessions.js', 'package.json',
    'symbol-compression.js',
)


def _atomic_bytes(destination: Path, data: bytes) -> None:
    """Replace one file atomically so Chrome never reads a partial build."""
    destination.parent.mkdir(parents=True, exist_ok=True)
    name = None
    try:
        with tempfile.NamedTemporaryFile(prefix='.chrome-build-', dir=destination.parent,
                                         delete=False) as stream:
            name = Path(stream.name)
            stream.write(data)
        os.replace(name, destination)
    finally:
        if name is not None:
            name.unlink(missing_ok=True)


def runtime_endpoint(environ: dict[str, str] | None = None) -> tuple[bool, str]:
    """Generate immutable per-build URL; the popup never accepts arbitrary URLs."""
    from urllib.parse import urlsplit
    variables = os.environ if environ is None else environ
    is_local = variables.get('IS_LOCAL', '1').strip().lower() in ('1', 'true', 'yes', 'on')
    if is_local:
        port = variables.get('PROMPT_HELPER_PORT', '5173')
        if not port.isascii() or not port.isdigit() or not 1 <= int(port) <= 65535:
            raise ValueError('PROMPT_HELPER_PORT must be 1..65535')
        return True, f'http://127.0.0.1:{int(port)}'
    value = variables.get('PROMPT_HELPER_PUBLIC_URL', '').strip()
    parsed = urlsplit(value)
    if (parsed.scheme != 'https' or not parsed.hostname or parsed.username or parsed.password or
        parsed.path not in ('', '/') or parsed.query or parsed.fragment):
        raise ValueError('IS_LOCAL=0 requires PROMPT_HELPER_PUBLIC_URL=https://your-host (origin only)')
    return False, f'https://{parsed.netloc}'


def build(destination: Path) -> tuple[Path, Path]:
    """Build in-place without replacing the directory Chrome has registered."""
    manifest = json.loads((SOURCE / 'manifest.json').read_text(encoding='utf-8'))
    if manifest.get('manifest_version') != 3:
        raise ValueError('Chrome extension must use Manifest V3')
    missing = [name for name in SOURCE_FILES if not (SOURCE / name).is_file()]
    if missing:
        raise FileNotFoundError('Chrome extension sources missing: ' + ', '.join(missing))
    destination = destination.expanduser().resolve()
    unpacked = destination / EXTENSION_FOLDER
    unpacked.mkdir(parents=True, exist_ok=True)
    for name in SOURCE_FILES:
        _atomic_bytes(unpacked / name, (SOURCE / name).read_bytes())
    is_local, endpoint = runtime_endpoint()
    config = (f'// Generated by plugins/chrome_live.py. Do not edit.\n'
              f'export const IS_LOCAL = {str(is_local).lower()};\n'
              f'export const CONFIGURED_ENDPOINT = {json.dumps(endpoint)};\n')
    _atomic_bytes(unpacked / 'runtime-config.js', config.encode('utf-8'))
    if not is_local:
        # Restrict the extension to the explicitly selected dashboard origin.
        manifest['host_permissions'].append(endpoint + '/*')
        manifest['content_scripts'][-1]['matches'].append(endpoint + '/*')
        _atomic_bytes(unpacked / 'manifest.json', (json.dumps(manifest, indent=2) + '\n').encode('utf-8'))
    build_info = {
        'build_id': uuid.uuid4().hex,
        'built_at': datetime.now(timezone.utc).isoformat(),
    }
    # build.json goes last: it is the signal that *all* files are updated.
    _atomic_bytes(unpacked / 'build.json', (json.dumps(build_info, sort_keys=True) + '\n').encode())
    archive = destination / (EXTENSION_FOLDER + '.zip')
    with tempfile.NamedTemporaryFile(prefix='.chrome-build-', suffix='.zip',
                                     dir=destination, delete=False) as stream:
        temporary_zip = Path(stream.name)
    try:
        with zipfile.ZipFile(temporary_zip, 'w', zipfile.ZIP_DEFLATED) as bundle:
            for name in (*SOURCE_FILES, 'build.json'):
                bundle.write(unpacked / name, arcname=name)
        os.replace(temporary_zip, archive)
    finally:
        temporary_zip.unlink(missing_ok=True)
    print(f'Unpacked Chrome extension: {unpacked}')
    print(f'ZIP distributable:        {archive}')
    print(f'Build ID (auto-reload):   {build_info["build_id"]}')
    print(f'Endpoint injected:       {endpoint} (IS_LOCAL={int(is_local)})')
    return unpacked, archive


def _json_object(path: Path) -> dict:
    try:
        data = json.loads(path.read_text(encoding='utf-8'))
        return data if isinstance(data, dict) else {}
    except (OSError, ValueError):
        return {}


def chrome_profiles_root(*, home: Path | None = None) -> Path | None:
    base = home if home is not None else Path.home()
    if sys.platform == 'darwin':
        return base / 'Library' / 'Application Support' / 'Google' / 'Chrome'
    if sys.platform.startswith('linux'):
        return base / '.config' / 'google-chrome'
    return None


def installed_profiles(unpacked: Path, *, home: Path | None = None) -> list[dict[str, str]]:
    """Read Chrome preferences only. Never modify Chrome's extension registry."""
    root = chrome_profiles_root(home=home)
    if root is None or not root.is_dir():
        return []
    wanted = unpacked.resolve()
    found = {}
    for profile in root.iterdir():
        if not profile.is_dir() or (profile.name != 'Default' and not profile.name.startswith('Profile ')):
            continue
        preferences = _json_object(profile / 'Preferences')
        profile_name = preferences.get('profile', {}).get('name', profile.name)
        for file_name in ('Preferences', 'Secure Preferences'):
            settings = _json_object(profile / file_name).get('extensions', {}).get('settings', {})
            if not isinstance(settings, dict):
                continue
            for extension_id, item in settings.items():
                if not isinstance(item, dict) or not isinstance(item.get('path'), str):
                    continue
                try:
                    installed_path = Path(item['path']).expanduser().resolve()
                except (OSError, ValueError):
                    continue
                if installed_path == wanted:
                    found[(profile.name, extension_id)] = {
                        'profile': str(profile_name),
                        'id': extension_id,
                        'enabled': str(item.get('state')) == '1',
                    }
    return list(found.values())


def _running() -> bool:
    try:
        return subprocess.run(['pgrep', '-x', 'Google Chrome'], capture_output=True,
                              text=True, check=False, timeout=5).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def _clipboard(value: str) -> bool:
    if shutil.which('pbcopy') is None:
        return False
    try:
        subprocess.run(['pbcopy'], input=value, text=True, check=True, timeout=5)
        return True
    except (OSError, subprocess.SubprocessError):
        return False


def _open_extensions() -> bool:
    try:
        # This opens a tab in an already running Google Chrome instance.
        return subprocess.run(['open', '-a', 'Google Chrome', CHROME_URL],
                              check=False, timeout=15).returncode == 0
    except (OSError, subprocess.SubprocessError):
        return False


def install(destination: Path, *, dry_run: bool = False, no_open: bool = False,
            home: Path | None = None) -> int:
    unpacked, _ = build(destination)
    if dry_run:
        print('DRY RUN: Chrome profile and windows untouched.')
        return 0
    if sys.platform != 'darwin':
        raise RuntimeError('The installer targets macOS Google Chrome. Use build-chrome-plugin elsewhere.')
    if not _running():
        raise RuntimeError('Google Chrome is not running. Open your existing Chrome browser first.')
    matches = installed_profiles(unpacked, home=home)
    if matches:
        for match in matches:
            suffix = '' if match['enabled'] else ' (disabled in profile)'
            print(f"Existing Chrome extension: {match['id']} in profile {match['profile']}{suffix}")
        print('Built files updated in place. The extension checks for new builds about every 30 seconds.')
        print('If upgrading from the old installer, click Reload ONCE on chrome://extensions')
        print('to activate the build watcher. Later builds are automatic.')
        return 0
    # Chrome does not support first-installing arbitrary unpacked extensions via
    # its normal command line. Perform the user's requested Load unpacked action
    # through the running Chrome UI; never edit Chrome's signed Preferences.
    script = ROOT / 'plugins' / 'chrome_first_install.applescript'
    if not script.is_file():
        raise RuntimeError(f'Missing Chrome UI installer: {script}')
    if shutil.which('osascript') is None:
        raise RuntimeError('osascript is required for installing into ordinary macOS Chrome.')
    if not _clipboard(str(unpacked)):
        raise RuntimeError('Cannot copy the unpacked extension directory to the macOS clipboard.')
    if no_open:
        print('No first-install automation requested (--no-open).')
        print('Load unpacked manually from chrome://extensions:', unpacked)
        return 0
    print('Installing into the CURRENT Google Chrome window using Load unpacked ...', flush=True)
    try:
        result = subprocess.run(['osascript', str(script), str(unpacked)], capture_output=True,
                                text=True, check=False, timeout=90)
    except subprocess.TimeoutExpired as exc:
        raise RuntimeError('Chrome UI installation timed out (90s). Check macOS Accessibility/Automation permissions.') from exc
    if result.returncode != 0:
        details = (result.stderr or result.stdout).strip()
        raise RuntimeError('Chrome UI installation could not be completed: ' + details +
                           f'\nManual fallback: chrome://extensions → Developer mode → Load unpacked → {unpacked}')
    # A dialog keystroke does not prove installation. Check the actual profile
    # registration and avoid printing "installed" on an unverified outcome.
    import time
    for _ in range(30):
        if (matches := installed_profiles(unpacked, home=home)):
            for match in matches:
                print(f"INSTALLED in Chrome profile {match['profile']} as {match['id']}")
            print('Later builds reload automatically in about 30 seconds.')
            return 0
        time.sleep(0.5)
    raise RuntimeError('Chrome received the Load unpacked interaction but its profile did not confirm installation. '
                       f'Check chrome://extensions for any error card. Extension directory: {unpacked}')


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('command', choices=('build', 'install'))
    parser.add_argument('--output', type=Path, default=DEFAULT_OUT)
    parser.add_argument('--dry-run', action='store_true')
    parser.add_argument('--no-open', action='store_true')
    args = parser.parse_args(argv)
    try:
        if args.command == 'build':
            build(args.output)
            return 0
        return install(args.output, dry_run=args.dry_run, no_open=args.no_open)
    except (OSError, ValueError, RuntimeError, KeyError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        return 1


if __name__ == '__main__':
    raise SystemExit(main())
